"""Commented-out code: comment blocks whose content is source code, not prose.

Only whole comment lines are considered, and a block is never split in a way
that leaves a dangling comment opener or closer. The score ("high" when almost
every line is code, "medium" when most are) is the static confidence; like every
other finding, each block is still verified by the LLM before it is removed.
"""
from __future__ import annotations

import re
from typing import List, Optional, Tuple

from ..inventory import Inventory, is_vendor
from ...models import Finding, Findings
from ...utils.text import SYNTAXES, block_safe, classify_lines, split_lines, strip_eol

SKIP_MARKERS = re.compile(
    r"copyright|licen[cs]e|\(c\)\s|©|all rights reserved|nosonar|eslint|jshint|jslint|noinspection|"
    r"@formatter|checkstyle|editor-fold|\$id[:$]|\$header|\$log[:$]|\$revision|#region|#endregion|"
    r"pragma|\[if\s|\[endif\]|#include|#exec|#echo|#config|#set\s|coding[:=]|@ts-|istanbul|pylint|"
    r"noqa|type:\s*ignore|fmt:\s|prettier-ignore|@license|@preserve|@cc_on|-\*-|vim:|@generated|"
    r"do not edit|auto-?generated|generated by|sourcemappingurl|sourceurl", re.I)
PROSE_START = re.compile(
    r"^(todo|fixme|xxx|hack|note|nota|ojo|bug|warning|warn|important|importante|pendiente|"
    r"@param|@return|@throws|@exception|@author|@version|@since|@see|@deprecated|@link|"
    r"@inheritdoc|@serial)\b", re.I)
WORD = re.compile(r"[A-Za-zÁÉÍÓÚÜÑáéíóúüñ]{2,}")
SEPARATOR = re.compile(r"[-=*_#/+~.<>|\\:;'\"\s]{3,}")

C_KEYWORD_DECL = re.compile(
    r"^(public|private|protected|static|final|var|let|const|function|class|interface|void|int|long|"
    r"boolean|bool|string|String|double|float|char|byte|short|decimal|object|import|package|using|"
    r"namespace|#include|#define|new)\b")
C_CONTROL = re.compile(r"^(if|for|foreach|while|switch|catch|else\s+if|using|lock|synchronized)\s*\(")
C_BLOCK_WORD = re.compile(r"^(else|try|finally|do)\b\s*\{?\s*$|^\}\s*(else|catch|finally)\b")
C_JUMP = re.compile(r"^(return|throw|break|continue|goto)\b[^?!]*;\s*$")
C_ASSIGN = re.compile(r"^[\w$.\[\]\"'()]+\s*(=|\+=|-=|\*=|/=|\|=|&=|\+\+|--)\s*[^=\s]?.*[;,]\s*$")
C_CALL = re.compile(r"^[\w$]+(\.[\w$]+|\[[^\]]*\])*\s*\(.*\)\s*;?\s*$")
ANNOTATION = re.compile(r"^@[A-Z][\w.]*(\(.*\))?\s*$")
XML_TAG_LINE = re.compile(r"^</?[A-Za-z][\w:.\-]*(\s|/?>|$)")
XML_TAG_NO_LT = re.compile(r"^[A-Za-z][\w:.\-]*\s+[\w:.\-]+\s*=\s*[\"']")
XML_ATTR_LINE = re.compile(r"^[\w:.\-]+\s*=\s*\"[^\"]*\"\s*(/?>)?\s*$")
SQL_LINE = re.compile(
    r"^(select|insert|update|delete|from|where|and|or|order\s+by|group\s+by|having|join|left|inner|"
    r"values|set|create|alter|drop|begin|end|exec|execute|declare|commit|rollback|union|into|"
    r"open|fetch|close|cursor)\b", re.I)
VB_LINE = re.compile(
    r"^(dim|set|let|call|redim|if\b.*\bthen|else|elseif|end\s+(if|sub|function|select|with|property|"
    r"type|enum)|for\s+\w+\s*=|for\s+each|next\b|loop\b|do\b|while\b|wend\b|select\s+case|case\b|"
    r"exit\s+(sub|function|do|for|property)|on\s+error|goto\b|resume\b|msgbox|private\s|public\s|"
    r"friend\s|sub\s|function\s|with\s|const\s|unload\s|load\s|me\.)", re.I)
VB_ASSIGN = re.compile(r"^[\w.()!]+\s*=\s*\S")
VB_MEMBER = re.compile(r"^[A-Za-z_]\w*(\.[A-Za-z_]\w*)+(\s+\S.*)?$")
COBOL_LINE = re.compile(
    r"^(move|perform|display|accept|if|else|end-if|compute|call|add|subtract|multiply|divide|"
    r"evaluate|when|end-evaluate|go\s+to|exec\s+sql|end-exec|read|write|rewrite|open|close|stop\s+run|"
    r"exit|initialize|string|unstring|inspect|set|search|copy|select|fd|01|05|10|15|77|88|goback|"
    r"continue|not\s+at\s+end|at\s+end)\b", re.I)
PY_LINE = re.compile(
    r"^(def|class|import|from|return|if|elif|else|for|while|try|except|finally|with|print|raise|"
    r"yield|lambda|pass|break|continue|assert|global|del)\b")
PY_ASSIGN = re.compile(r"^[\w.\[\]'\"]+\s*(=|\+=|-=)\s*[^=\s]")
SHELL_LINE = re.compile(
    r"^(export|echo|cd|rm|cp|mv|mkdir|java|javac|sh|bash|source|set|if|then|fi|for|do|done|case|esac|"
    r"while|exec|chmod|chown|ant|mvn|cat|grep|sed|awk|nohup|sleep|kill)\b")
PROP_LINE = re.compile(r"^[\w.\-\[\]/]+\s*[=:]\s*\S")
PASCAL_LINE = re.compile(r"(:=|^begin\b|^end\s*[;.]|^procedure\s|^function\s|^if\b.*\bthen\b|;\s*$)", re.I)
BAT_LINE = re.compile(r"^(@?echo|set|call|goto|if|copy|xcopy|del|java|cd|start|for|rem|exit|pause)\b", re.I)
CSS_LINE = re.compile(r"(\{\s*$|^\}\s*$|^[\w-]+\s*:\s*[^;]+;\s*$)")

FAMILY = {"c": "c", "css": "css", "xml": "xml", "jsp": "jsp", "vb": "vb", "sql": "sql",
          "hash": "hash", "pascal": "pascal", "bat": "bat", "ini": "ini", "cobol": "cobol"}


def _clean(text: str) -> str:
    s = text.strip()
    s = re.sub(r"^\*+\s?", "", s)        # javadoc-style continuation
    s = re.sub(r"^!\s?", "", s)          # properties '!' comments
    return s.strip()


def _prose(s: str) -> bool:
    words = WORD.findall(s)
    has_punct = any(ch in s for ch in ";{}=()<>[]")
    if len(words) >= 4 and not has_punct:
        return True
    return s.endswith((".", "?", "!")) and len(words) >= 3 and not s.endswith(");")


def line_score(text: str, family: str, ext: str) -> Tuple[int, bool]:
    """(+1 code / -1 prose / 0 neutral, strong-code flag) for one comment line."""
    s = _clean(text)
    if not s or SEPARATOR.fullmatch(s):
        return 0, False
    if PROSE_START.match(s):
        return -1, False
    if family in ("c", "jsp", "css", "pascal"):
        if re.fullmatch(r"[{}()\s;]+", s):
            return 1, True
        if family == "css" and CSS_LINE.search(s):
            return 1, True
        if family == "pascal" and PASCAL_LINE.search(s):
            return 1, s.endswith(";")
        if C_CONTROL.match(s) or C_BLOCK_WORD.match(s) or C_JUMP.match(s) or ANNOTATION.match(s):
            return 1, True
        if C_KEYWORD_DECL.match(s) and any(ch in s for ch in ";{(="):
            return 1, True
        if C_ASSIGN.match(s) or C_CALL.match(s):
            return 1, s.endswith((";", "{", "}"))
        if s.endswith((";", "{")) and not _prose(s):
            return 1, True
    if family in ("xml", "jsp"):
        if XML_TAG_LINE.match(s) or XML_TAG_NO_LT.match(s) or XML_ATTR_LINE.match(s):
            return 1, True
    if family == "sql" or (family == "c" and ext in ("sql",)):
        if SQL_LINE.match(s) and (s.upper() == s or any(ch in s for ch in ",=;(")):
            return 1, s.endswith(";")
    if family == "vb":
        if VB_LINE.match(s) or (VB_ASSIGN.match(s) and len(WORD.findall(s.split("=", 1)[1])) <= 4) \
                or VB_MEMBER.match(s):
            return 1, True
    if family == "cobol":
        if COBOL_LINE.match(s) and s.upper() == s:
            return 1, True
    if family == "hash":
        if ext == "py" and (PY_LINE.match(s) and (s.endswith(":") or "(" in s or "=" in s or " " not in s)):
            return 1, True
        if ext == "py" and PY_ASSIGN.match(s) and len(WORD.findall(s)) <= 6:
            return 1, False
        if ext in ("sh", "bash", "ksh", "zsh", "csh") and SHELL_LINE.match(s) and any(ch in s for ch in "=$-/\"'"):
            return 1, False
        if ext in ("properties", "conf", "cfg", "yml", "yaml", "toml", "ini") and PROP_LINE.match(s) \
                and not _prose(s.split("=", 1)[-1].split(":", 1)[-1]):
            key = re.split(r"[=:]", s, 1)[0].strip()
            if " " not in key and (("." in key) or ("_" in key) or key.islower() or key.isupper()):
                return 1, True
    if family == "ini" and PROP_LINE.match(s):
        return 1, True
    if family == "bat" and BAT_LINE.match(s) and any(ch in s for ch in "=%\\/"):
        return 1, False
    return (-1 if _prose(s) else 0), False


def score_block(texts: List[str], family: str, ext: str) -> Optional[str]:
    scores = [line_score(t, family, ext) for t in texts]
    code = sum(1 for s, _ in scores if s > 0)
    prose = sum(1 for s, _ in scores if s < 0)
    if code == 0:
        return None
    strong = any(st for s, st in scores if s > 0)
    ratio = code / (code + prose)
    if ratio >= 0.85 and (code >= 2 or strong):
        return "high"
    if ratio >= 0.5:
        return "medium"
    return None


def comment_runs(kinds: List[str]) -> List[Tuple[int, int]]:
    runs: List[Tuple[int, int]] = []
    start = None
    for i, kind in enumerate(kinds, start=1):
        if kind == "comment":
            start = start or i
        else:
            if start:
                runs.append((start, i - 1))
            start = None
    if start:
        runs.append((start, len(kinds)))
    return runs


def detect_commented_code(inv: Inventory, findings: Findings) -> None:
    for fi in inv.files:
        if fi.excluded or fi.generated or fi.rel in inv.junk or not fi.syntax or is_vendor(fi.rel):
            continue
        if fi.kind not in ("source", "web", "script", "db", "config", "build"):
            continue
        syn = SYNTAXES.get(fi.syntax)
        text = inv.text(fi)
        if not syn or not text:
            continue
        lines = split_lines(text)
        if any(len(line) > 3000 for line in lines[:200]):
            continue  # minified or generated
        cl = classify_lines(lines, syn)
        family = FAMILY.get(fi.syntax, "c")
        for idx, (start, end) in enumerate(comment_runs([li.kind for li in cl.lines])):
            infos = cl.lines[start - 1:end]
            if any(li.doc for li in infos):
                continue
            texts = [li.text for li in infos]
            joined = "\n".join(texts)
            if SKIP_MARKERS.search(joined):
                continue
            if fi.ext == "py" and start <= 2 and lines[0].startswith("#!"):
                continue
            level = score_block(texts, family, fi.ext)
            if not level or not block_safe(cl, start, end):
                continue
            snippet = "\n".join(strip_eol(x) for x in lines[start - 1:min(end, start + 11)])
            n = end - start + 1
            findings.add(Finding(
                category="commented_code", subtype="commented_out_code", path=fi.rel,
                start_line=start, end_line=end,
                reason=f"{n} línea(s) de código comentado",
                confidence=level, needs_llm=(level != "high"), detectors=["comments"],
                evidence=[f"bloque de comentario con contenido de código ({level})"],
                snippet=snippet,
                edit={"op": "delete_lines", "ranges": [[start, end]]}))
